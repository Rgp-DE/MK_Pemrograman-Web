<?php

session_start();

/*
|--------------------------------------------------------------------------
| Hapus Semua Data Session
|--------------------------------------------------------------------------
*/

$_SESSION = [];


/*
|--------------------------------------------------------------------------
| Hapus Session Cookie
|--------------------------------------------------------------------------
*/

if (ini_get("session.use_cookies")) {

    $params = session_get_cookie_params();

    setcookie(
        session_name(),
        '',
        time() - 42000,
        $params["path"],
        $params["domain"],
        $params["secure"],
        $params["httponly"]
    );
}


/*
|--------------------------------------------------------------------------
| Hancurkan Session
|--------------------------------------------------------------------------
*/

session_destroy();


/*
|--------------------------------------------------------------------------
| Buat Session Baru Untuk Flash Message
|--------------------------------------------------------------------------
*/

session_start();

$_SESSION['flash'] = [
    'type' => 'success',
    'pesan' => 'Anda berhasil logout.'
];


/*
|--------------------------------------------------------------------------
| Kembali ke Beranda
|--------------------------------------------------------------------------
*/

header('Location: ../index.php');
exit;